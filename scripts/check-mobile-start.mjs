// Run with a local Vite server. Test-only browser interception exposes the live engine;
// server requests are blocked, so test runs never submit scores or profiles.
import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const base = process.argv[2] ?? 'http://127.0.0.1:5175'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ?? chromium.executablePath() })
try {
  const page = await browser.newPage({viewport:{width:390,height:780},hasTouch:true})
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.route('**/*',route=>new URL(route.request().url()).origin===new URL(base).origin?route.continue():route.abort())
  await page.route('**/src/hooks/useGameEngine.ts*',async route=>{
    const response=await route.fetch()
    const body=(await response.text()).replace('instance.onStateChange(store.update);','instance.onStateChange(store.update); window.__startReview = {engine:instance,store};')
    await route.fulfill({response,body})
  })
  await page.goto(base)
  await page.getByRole('button',{name:'혼자 하기',exact:true}).click()
  const input=page.getByRole('textbox',{name:'단어 입력'})
  await page.getByPlaceholder('눌러서 시작').waitFor()
  await page.waitForFunction(()=>window.__startReview.store.getSnapshot()?.phase==='paused')
  assert.equal(await page.locator('[data-pause]').count(),0)
  const elapsed=await page.evaluate(()=>window.__startReview.store.getSnapshot().stats.durationSec)
  await page.waitForTimeout(600)
  assert.equal(await page.evaluate(()=>window.__startReview.store.getSnapshot().stats.durationSec),elapsed)
  await input.click()
  assert.equal(await page.locator('.mp-game').getAttribute('data-phase'),'paused')
  await page.setViewportSize({width:390,height:450})
  await page.waitForTimeout(50)
  assert.equal(await page.locator('.mp-game').getAttribute('data-phase'),'paused')
  await page.waitForFunction(()=>window.__startReview.store.getSnapshot()?.phase==='playing')
  assert(await input.evaluate(element=>element===document.activeElement))
  // Explanation actions replace the input visually, directly above the keyboard.
  const next=page.getByRole('button',{name:'시작하기',exact:true})
  const nextRect=await next.boundingBox()
  const inputRow=await page.locator('.mp-input').boundingBox()
  assert(nextRect.y>=inputRow.y && nextRect.y+nextRect.height<=inputRow.y+inputRow.height)
  assert(nextRect.width>=inputRow.width-20)
  assert.equal(await input.evaluate(element=>getComputedStyle(element).opacity),'0')
  await page.getByRole('button',{name:'시작하기',exact:true}).tap()
  assert.equal(await page.evaluate(()=>window.__startReview.store.getSnapshot().stage.tutorialStep),1)
  assert.equal(await page.locator('[data-tutorial-next]').count(),0)
  assert.equal(await input.evaluate(element=>getComputedStyle(element).opacity),'1')
  await input.fill('책')
  assert(await input.evaluate(element=>element===document.activeElement))
  assert.equal(await page.locator('[data-pause]').count(),0)
  assert(!(await page.locator('.mp-tutorial').textContent()).includes('Enter'))
  for (const height of [450,350,320]) {
    await page.setViewportSize({width:390,height})
    await page.waitForTimeout(100)
    const guide=await page.locator('.mp-tutorial').boundingBox()
    const arena=await page.locator('.mp-arena').boundingBox()
    const field=await input.boundingBox()
    assert(guide.y+guide.height<=arena.y+1, 'Guide must not cover canvas')
    assert(arena.height>0 && field.y+field.height<=height, 'Canvas and input remain visible')
  }
  await input.press('Enter')
  assert.equal(await page.evaluate(()=>window.__startReview.store.getSnapshot().stage.tutorialStep),2)
  await page.getByRole('button',{name:'일시정지',exact:true}).click()
  await page.locator('[data-pause]').waitFor()
  await page.getByRole('button',{name:'계속하기',exact:true}).click()
  assert.equal(await page.locator('.mp-game').getAttribute('data-phase'),'playing')
  await input.evaluate(element=>element.blur())
  await page.locator('[data-pause]').waitFor()
  await page.getByRole('button',{name:'다시 하기',exact:true}).click()
  await page.getByPlaceholder('눌러서 시작').waitFor()
  await page.waitForFunction(()=>window.__startReview.store.getSnapshot()?.phase==='paused')
  assert.equal(await page.locator('[data-pause]').count(),0)
  // Losing focus while the keyboard is opening must cancel the delayed start.
  await input.click()
  await input.evaluate(element=>element.blur())
  await page.waitForTimeout(600)
  assert.equal(await page.locator('.mp-game').getAttribute('data-phase'),'paused')
  await input.click()
  await page.waitForFunction(()=>window.__startReview.store.getSnapshot()?.phase==='playing')
  await page.evaluate(() => localStorage.setItem('typing-stacker/display/v1', JSON.stringify({shake:0,glow:0,trail:0,soloTutorial:'disabled'})))
  await page.goto(base)
  await page.getByRole('button',{name:'혼자 하기',exact:true}).click()
  await page.getByPlaceholder('눌러서 시작').waitFor()
  await page.waitForFunction(()=>window.__startReview.store.getSnapshot()?.phase==='paused')
  assert.equal(await page.locator('[data-pause]').count(),0)
  await input.click()
  await page.waitForFunction(()=>window.__startReview.store.getSnapshot()?.phase==='playing')
  assert.equal(await page.evaluate(()=>window.__startReview.store.getSnapshot().stage.id),1)
  assert.deepEqual(errors,[])
  console.log('PASS initial input start, viewport settling, tutorial Next touch and keyboard input, compact layout, pause/resume, blur, restart, and cancelled start')
} finally {await browser.close()}
