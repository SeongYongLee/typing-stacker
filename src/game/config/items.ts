/**
 * 물건이 나오는 방식 — **무엇이 떨어지고 어디에 얹히는가**.
 */

/**
 * **합성했을 때** 공중에 놓이는 작은 통나무.
 *
 * 판을 끝내는 것은 점수가 아니라 얹을 자리가 좁아지는 것이니, 자리를 하나 더 주는
 * 것이 이 게임의 말로 된 보상이다. 규칙은 `systems/Ledge.ts`에, 왜 합성에만
 * 주는지는 `GameEngine.growLedge`에.
 *
 * **폭은 가장 큰 물건이 온전히 얹히는 값이다.** `MAX_ITEM_HALF_WIDTH`(0.55)보다
 * 좁으면 비행기·자전거가 양쪽으로 삐져나와 놓자마자 굴러떨어진다 — 새 자리를 줬는데
 * 쓸 수 있는 물건이 따로 있는 셈이 된다.
 *
 * 받침대 그림(`stack-platform-log.png`)을 줄여서 쓴다. 새 아트가 필요 없고,
 * 무엇보다 **같은 그림이라 "받침대다"가 설명 없이 읽힌다.**
 */
const LEDGE = {
  /**
   * 반폭은 이 사이에서 판마다 다르게 뽑는다.
   *
   * 같은 길이만 나오면 세 개가 서도 "같은 것이 세 번"이지 새로운 자리로 안 읽힌다.
   * 짧은 것은 한 칸짜리 기둥, 긴 것은 두어 개를 나란히 놓을 수 있는 자리가 된다.
   *
   * **아래끝은 `MAX_ITEM_HALF_WIDTH`(0.55)보다 커야 한다.** 좁으면 비행기·자전거가
   * 양쪽으로 삐져나와 놓자마자 굴러떨어진다 — 새 자리를 줬는데 쓸 수 있는 물건이
   * 따로 있는 셈이 된다.
   */
  minHalfWidth: 0.6,
  maxHalfWidth: 0.95,
  halfHeight: 0.14,
  /** 받침대 윗면에서 이만큼은 떠 있어야 한다. 붙으면 그 아래로 물건이 못 들어간다 */
  minClearance: 1,
  /** 한 판에 이만큼까지. 무제한이면 나중에 공중이 발판으로 즐비해진다 */
  maxCount: 3,
  /** 물건이나 다른 통나무와 이만큼은 떨어져야 한다 */
  margin: 0.18,
  /**
   * 히든 연출이 뭉쳐 통나무가 되기까지의 시간(초).
   *
   * **이 시간이 다 지난 뒤에 실제로 세운다.** 먼저 세워두고 연출만 얹으면 아직 보이지도
   * 않는 통나무가 물건을 받아내서, 허공에 걸린 것처럼 보인다.
   */
  formSec: 0.85,
} as const

/**
 * 화이트보드에 적힌 단어를 쳤을 때 받침대 밖에서 받아 가는 **회수 손**(`systems/Catcher.ts`).
 *
 * 통나무(`LEDGE`)와 반대되는 물건이다. 저쪽은 자리를 **주는** 보상이고 이쪽은 물건을
 * **치워주는** 배출구다 — 그래서 값의 성격도 반대다. 통나무는 넓고 평평하고 오래
 * 남아야 하고, 이 판은 좁고 기울고 잠깐이어야 한다.
 */
const CATCH = {
  /**
   * 회수되는 물건이 떨어지는 자리(가운데에서 이만큼, 단어가 있던 레인 쪽).
   *
   * 받침대 밖이지만 아레나 안쪽이다. 안쪽에 떨어뜨려 팔로 미끄러뜨리면 팔 위에서
   * 멈췄다가 필드로 되돌아오는 실패가 생긴다. 처음부터 바깥 손 위에 떨구면
   * "회수"가 규칙과 화면 모두에서 같다.
   */
  dropX: 2.45,
  /** 탑 꼭대기에서 이만큼 떠서 생긴다. 탑 속에 생기면 회수가 아니라 붕괴다 */
  rise: 0.55,
  /**
   * 기울기(가로 1당 세로). `tan 20°`쯤이다.
   *
   * 완만하면 물건이 판 위에 멈춰 공중 발판이 되고, 가파르면 받는 순간 튕겨나가
   * "회수됐다"가 아니라 "쳐냈다"로 보인다.
   */
  slope: 0.36,
  /**
   * 판이 머무는 시간(초).
   *
   * 물건이 스폰 높이에서 판까지 떨어지고, 그 뒤 미끄러져 나갈 때까지다. 이 타이머는
   * 실제 물건이 생기는 순간부터 흐른다. 더 짧으면 팔 위에서 멈춘 물건이 팔이 사라진 뒤
   * 다시 필드로 떨어진다.
   */
  holdSec: 2.6,
  /**
   * 판의 두께(반). 통나무(0.14)보다 얇다 — 받쳐주는 자리가 아니라 스쳐 보내는 판이다.
   *
   * 너무 얇게 두지 않는 것은 물리 쪽 제약이다. 얇은 도형은 빠르게 떨어지는 물건이
   * 한 스텝에 뚫고 지나갈 수 있고, 그러면 회수가 아니라 **아무 일도 안 일어난 것**이 된다.
   */
  halfThickness: 0.1,
} as const

/**
 * 히든 대체 결과가 있는 조합이 기본 결과 대신 히든 형태를 내놓을 확률.
 *
 * 단어 입력은 항상 기본 물건을 떨어뜨린다. 히든은 같은 속성의 재료를 조합했을 때
 * 만나는 보상으로만 남긴다.
 */
const HIDDEN_CHANCE = 0.34

export { LEDGE, CATCH, HIDDEN_CHANCE }
