/**
 * 물건이 나오는 방식 — **무엇이 떨어지고 어디에 얹히는가**.
 */

/**
 * **합성했을 때** 공중에 놓이는 작은 통나무.
 *
 * 판을 끝내는 것은 점수가 아니라 얹을 자리가 좁아지는 것이니, 자리를 하나 더 주는
 * 것이 이 게임의 말로 된 보상이다. 규칙은 `systems/Ledge.ts`에, 왜 합성에만
 * 주는지는 `GameEngine.growLedge`에.
 *
 * **폭은 가장 큰 물건이 온전히 얹히는 값이다.** `MAX_ITEM_HALF_WIDTH`(0.55)보다
 * 좁으면 비행기·자전거가 양쪽으로 삐져나와 놓자마자 굴러떨어진다 — 새 자리를 줬는데
 * 쓸 수 있는 물건이 따로 있는 셈이 된다.
 *
 * 받침대 그림(`stack-platform-log.png`)을 줄여서 쓴다. 새 아트가 필요 없고,
 * 무엇보다 **같은 그림이라 "받침대다"가 설명 없이 읽힌다.**
 */
const LEDGE = {
  /**
   * 반폭은 이 사이에서 판마다 다르게 뽑는다.
   *
   * 같은 길이만 나오면 세 개가 서도 "같은 것이 세 번"이지 새로운 자리로 안 읽힌다.
   * 짧은 것은 한 칸짜리 기둥, 긴 것은 두어 개를 나란히 놓을 수 있는 자리가 된다.
   *
   * **아래끝은 `MAX_ITEM_HALF_WIDTH`(0.55)보다 커야 한다.** 좁으면 비행기·자전거가
   * 양쪽으로 삐져나와 놓자마자 굴러떨어진다 — 새 자리를 줬는데 쓸 수 있는 물건이
   * 따로 있는 셈이 된다.
   */
  minHalfWidth: 0.6,
  maxHalfWidth: 0.95,
  halfHeight: 0.14,
  /** 받침대 윗면에서 이만큼은 떠 있어야 한다. 붙으면 그 아래로 물건이 못 들어간다 */
  minClearance: 1,
  /** 한 판에 이만큼까지. 무제한이면 나중에 공중이 발판으로 즐비해진다 */
  maxCount: 3,
  /** 물건이나 다른 통나무와 이만큼은 떨어져야 한다 */
  margin: 0.18,
  /**
   * 히든 연출이 뭉쳐 통나무가 되기까지의 시간(초).
   *
   * **이 시간이 다 지난 뒤에 실제로 세운다.** 먼저 세워두고 연출만 얹으면 아직 보이지도
   * 않는 통나무가 물건을 받아내서, 허공에 걸린 것처럼 보인다.
   */
  formSec: 0.85,
} as const

/**
 * 히든을 가진 단어를 맞췄을 때 히든이 나올 확률.
 *
 * 이 값만으로는 체감을 알 수 없다. 실제로 보이는 빈도는
 * `히든을 가진 단어 수 / 전체 단어 수` 를 곱한 값이다. 물건을 20종에서 57종으로
 * 늘리면서 단어가 13개에서 50개가 됐는데 히든은 7개 그대로여서, 판당 기대 히든이
 * 1.5개에서 0.41개로 떨어졌다 — 대부분의 판에서 하나도 못 본다.
 *
 * 그래서 0.14에서 0.35까지 올렸는데, 그건 **종류가 적은 것을 빈도로 가린 것**이라
 * 같은 일곱 개가 자주 나오는 부작용이 따라왔다. 제대로 된 해법은 히든을 가진
 * 단어를 늘리는 것이고, 늘어난 만큼 이 값을 도로 낮춘다.
 *
 * | | 히든 보유 단어 | 확률 | 판당 기대 |
 * |---|---|---|---|
 * | 물건 20종 시절 | 7 / 13 | 0.14 | 1.5 |
 * | 57종 직후 | 7 / 50 | 0.14 | 0.39 |
 * | 빈도로 가린 것 | 7 / 50 | 0.35 | 0.98 |
 * | 문어·트리를 히든으로 | 9 / 48 | 0.26 | 0.98 |
 * | 지금 (합성 세트) | 11 / 78 | 0.34 | 0.96 |
 *
 * 판당 기대는 그대로 두고 종류만 늘린다 — 늘어난 것이 빈도로 나타나면 히든이
 * "가끔 나오는 다른 형태"이기를 그친다. `tests/ItemResolver.test.ts`가 이 기대치를
 * 위아래로 지켜본다.
 *
 * 합성 세트에서 값이 도로 올라간 것은 **재료 30종이 전부 단어이기 때문**이다. 분모가
 * 48에서 78로 뛰는 동안 히든은 둘밖에 안 늘었다. 다만 이번에는 히든이 유일한
 * "특별한 물건"이 아니다 — 합성 전용 18종이 생겼고 그쪽은 확률이 아니라 손으로 얻는다.
 * 그래서 여기를 더 밀어올리지 않는다.
 */
const HIDDEN_CHANCE = 0.34

/**
 * 첫 밤(밭이 좁혀져 있는 동안)의 히든 확률.
 *
 * 첫 밤의 밭은 **같은 물건 둘짜리 레시피의 재료**만 내보내는데, 그 재료는 전부
 * 히든 보유 단어다 — 같은 것 둘의 결과물이 곧 그 단어의 히든이니 구조적으로 그렇다.
 * 그래서 첫 밤에는 드롭마다 히든 확률이 걸리고, 같은 확률이라도 밀도가 뛴다.
 *
 * **누르는 값이지 끄는 값이 아니다.** 목표는 첫 밤을 낮과 **같은 밀도**로 만드는 것이다 —
 * 히든이 몰리는 구간이 되어도 안 되고, 마르는 구간이 되어도 안 된다.
 *
 * ## 이 값은 밭의 구성이 정한다
 *
 * 맞춰야 할 값은 `HIDDEN_CHANCE x 평소의 히든 보유 단어 비율 ÷ 첫 밤 밭의 비율`이다.
 * 첫 밤 밭은 언제나 100%이므로 결국 **평소 비율이 이 값을 정하고**, 그 비율은 아트가
 * 올 때마다 움직인다. 상수만 보고 고치면 어긋난다.
 *
 * | 시점 | 평소 비율 | 첫 밤 배율 | 맞는 값 |
 * |---|---|---|---|
 * | 2026-08-08 | 14% (78단어 중 11) | 7.1배 | 0.05 |
 * | **2026-08-09 (지금)** | **35%** (107단어 중 37) | **2.89배** | **0.12** |
 *
 * 0.05를 그대로 두었더니 첫 밤이 **평소보다도 마른 구간**이 됐다 — 눈에 보이는 히든
 * 비율이 낮 12%인데 첫 밤이 5%였다. 누르려던 것이 지나쳤던 것이다.
 *
 * 실측(`tests/zz-balance.measure.test.ts`, 봇 60판 · 2026-08-09):
 *
 * | 값 | 판당 히든 | 못 본 판 | 특별한 것 합계 | 아무것도 못 본 판 |
 * |---|---|---|---|---|
 * | 0.05 (예전) | 0.97 | 43% | 1.82 | 13% |
 * | **0.12 (지금)** | **1.27** | **30%** | **2.02** | **7%** |
 * | 0.20 | 1.97 | 13% | 2.67 | 3% |
 *
 * 0.20으로 더 올리지 않은 것은 그쯤이면 첫 밤이 다시 **히든이 몰리는 구간**이 되어
 * 이 값을 만든 이유로 되돌아가기 때문이다.
 *
 * **전체 확률(`HIDDEN_CHANCE`)을 낮춰서 풀면 안 된다.** 원인이 확률이 아니라 첫 밤
 * 밭의 구성이라, 전체를 건드리면 그 뒤의 구간까지 함께 마르고 그쪽은 이 프로젝트가
 * "히든이 너무 적다"에서 시작했던 자리다.
 *
 * 0으로 두지 않은 이유는 **첫 밤에도 "무엇이 나올까"가 남아야** 하기 때문이다.
 * 다만 히든이 나오면 그것은 이미 결과물이라 재료가 하나 사라진다 — 그래서 이 값을
 * 낮추면 첫 합성이 빨라지고, 올리면 늦어진다.
 */
const OPENING_HIDDEN_CHANCE = 0.12

export { LEDGE, HIDDEN_CHANCE, OPENING_HIDDEN_CHANCE }
