/**
 * 판의 시간 — **언제 무엇이 내려오는가**.
 *
 * 난이도는 시간이 아니라 **탑 높이**를 따라가고(`DIFFICULTY_FULL_HEIGHT`), 시간이
 * 정하는 것은 어떤 단어가 내려오는가 하나뿐이다(`DayNight.ts`). 압박의 축을 둘로
 * 늘리면 서로 겹쳐서 어느 쪽이 판을 끝냈는지 알 수 없게 된다.
 */

/**
 * 대전에서 판이 열리기 전에 세는 초.
 *
 * 누르는 순간 바로 시작하면 첫 단어가 이미 내려오고 있다 — 누른 사람은 마우스에
 * 손이 가 있고 자판으로 옮길 틈이 없다. 대전에는 이유가 하나 더 있다: 마지막에
 * 준비를 누른 사람이 아니면 언제 열리는지 모른 채 당한다. **남은 시간을 알려주는
 * 것 자체가 일**이라 숫자를 센다.
 *
 * 혼자 할 때는 그 두 번째 이유가 없어서 세지 않는다 — 아래 `SOLO_*`를 볼 것.
 */
const COUNTDOWN_SEC = 3

/**
 * 혼자 하기는 숫자를 세지 않고 **READY → START** 두 박자로 연다.
 *
 * 대전에서 숫자를 세는 이유는 손을 옮길 틈 말고 하나가 더 있다 — 마지막에 준비를
 * 누른 사람이 아니면 언제 열리는지 모른 채 당한다. 혼자 할 때는 방금 자기가 눌렀으니
 * 그 이유가 없고, 남는 것은 손을 옮길 틈뿐이다. 그 틈에 셋을 세면 다시 하기를
 * 되풀이할 때 길게 느껴진다.
 *
 * READY가 길고 START가 짧다. 손을 부르는 데는 시간이 걸리지만 놓아주는 것은
 * 신호 하나면 된다 — 길이가 같으면 둘 다 대기로 읽힌다.
 */
const SOLO_READY_MS = 750

const SOLO_START_MS = 450

/**
 * 받침대 위로 이만큼 쌓으면 단어 밀도가 최대치에 닿는다(`Difficulty`).
 *
 * 예전에는 이 값을 따로 두지 않고 **카메라가 움직이기 시작하는 높이**에서 끌어 썼다
 * (`CAMERA_START_TOP - platformTop` = 1.2m). "판이 본격적으로 시작됐다는 것을 눈으로
 * 아는 순간"과 밀도가 오르는 시점을 맞추려던 것이었는데, 재보니 **그 지점이 판의
 * 절반**이었다. 나머지 절반을 내내 최대 밀도로 보내는 셈이다.
 *
 * 봇 40판 실측(판 길이 44.0초 · 19.4드롭 · 최고 높이 평균 2.18m):
 *
 * | 기준 | 최대 밀도까지 | 판의 몇 % 지점 | 끝까지 못 닿은 판 |
 * |---|---|---|---|
 * | 1.2m (예전) | 22.6초 · 8.8드롭 | **52%** | 3/40 |
 * | **1.6m (지금)** | 31.2초 · 13.2드롭 | **68%** | 10/40 |
 * | 2.0m | 37.7초 · 16.5드롭 | 78% | 18/40 |
 *
 * **못 닿는 판이 생기는 것은 흠이 아니라 뜻한 바다.** 난이도가 높이를 따라가는 이유가
 * "잘 쌓는 사람에게 더 많은 단어가 오고 아직 못 쌓은 사람은 여유를 갖는다"인데,
 * 1.2m에서는 거의 모든 판이 최대치를 봤으니 그 규칙이 사실상 꺼져 있었다. 1.6m면
 * 네 판 중 한 판은 끝까지 여유롭게 간다.
 *
 * 2.0m까지 밀지 않은 이유는 절반 가까운 판이 최대 밀도를 아예 못 보기 때문이다.
 * 그쯤 되면 밀도가 오르는 규칙 자체가 있으나 마나 하다.
 *
 * 카메라와의 연결이 끊어진 것은 알고 한 것이다. 카메라가 움직이는 순간은 여전히
 * "이제 시작"의 신호이고, 밀도는 그 뒤로 조금 더 오른다.
 */
const DIFFICULTY_FULL_HEIGHT = 1.6

/**
 * 첫 밤을 끝내는 합성 횟수.
 *
 * **첫 밤은 시간이 아니라 사건으로 끝난다.** 2재료 레시피를 집중하는 구간이고
 * 목적이 "합성이라는 것이 있다"를 알리는 것이므로, 알린 그 순간이 끝나는 지점이다.
 * 시간이나 드롭 수로 끊으면 느린 사람은 배우기 전에 풀리고 빠른 사람은 이미 아는
 * 것을 계속 본다.
 *
 * **둘인 이유는 한 번은 우연일 수 있기 때문이다.** 한 번만 보고 넘어가면 그것이
 * 규칙인지 사고인지 모른 채 흐름이 바뀐다. 두 번째는 "또 되네"라서 규칙이 된다.
 * 새 레시피 흐름의 도달률과 시각은 `zz-recipe-flow.measure.test.ts`에서 잰다.
 */
const FIRST_NIGHT_MERGES = 2

/**
 * 첫 밤의 **상한**(초). 이 시간을 넘기면 합성을 못 했어도 낮으로 넘어간다.
 *
 * 없으면 합성을 한 번도 못 한 사람이 판 전체를 쉬운 레시피 집중 구간으로 보낸다.
 * 35초는 정상적인 판보다 막힌 판을 풀어주는 안전장치로 둔다.
 */
const FIRST_NIGHT_SEC = 35

/**
 * 낮과 밤의 길이(초).
 *
 * 첫 밤이 끝나면 낮과 밤이 번갈아 돈다. 밤에는 레시피 재료의 연속 상한이 늘어
 * 다른 물건도 나오면서 합성 기회가 더 촘촘해진다.
 *
 * **30/15에서 20/10으로 줄였다.** 판 길이와 안 맞았기 때문이다 — 봇 60판에서
 * 판 중앙값이 **37초**인데 밤이 `첫 밤 15 + 낮 30 = 45초`부터 시작해서, **밤에 닿는
 * 판이 28%뿐이고 판당 밤에 머문 시간이 2.8초**(드롭 한 개)였다. 몰아치라고 만든
 * 구간을 열 판 중 일곱이 아예 못 봤다.
 *
 * 예전에 밤의 밭을 레시피 3·5·8개로 좁히는 것만으로는 갖춰지는 양이 0.33~0.40으로
 * 차이가 없었다. 지금은 한 레시피의 부족한 재료를 가까이 내보낸다. 낮:밤 = 2:1은
 * 그대로 두었고 시계 눈금도 그 비율을 그린다.
 */
const DAY_SEC = 20

const NIGHT_SEC = 10

/** 물건을 연달아 쏟아내 물리를 망가뜨리는 것만 막는 최소 간격 */
const DROP_COOLDOWN_MS = 300

const WORD = {
  /*
   * 좌우 각 칸 수. 여기 × 2가 화면에 동시에 뜰 수 있는 단어의 상한이다.
   *
   * 대전에서 사람이 늘면 단어를 더 내보내는데(Difficulty.forPlayers), 칸이 딱 맞으면
   * 자리를 못 찾아 조용히 걸러진다. 여유를 두어야 여덟이 붙어도 밭이 채워진다.
   */
  slotsPerSide: 5,
} as const

export { COUNTDOWN_SEC, SOLO_READY_MS, SOLO_START_MS, DIFFICULTY_FULL_HEIGHT, FIRST_NIGHT_MERGES, FIRST_NIGHT_SEC, DAY_SEC, NIGHT_SEC, DROP_COOLDOWN_MS, WORD }
