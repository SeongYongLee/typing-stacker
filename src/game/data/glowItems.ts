/**
 * 얹힐 때 화면을 물들이는 물건.
 *
 * 처음에는 **모든** 물건이 제 색으로 화면을 물들이게 했다. 물건마다 색이 다르니
 * 특색이 되긴 했는데, 1초에 한 번씩 화면 색이 바뀌면 그것은 특색이 아니라 배경이
 * 깜빡이는 것이다 — 늘 일어나는 일은 아무것도 알리지 못한다.
 *
 * ## 무엇이 "특수한" 물건인가
 *
 * 희귀도로 가르지 않는다. 번개는 히든도 합성 전용도 아닌 평범한 단어 물건인데,
 * 번개가 떨어질 때 화면이 노랗게 물드는 것은 자연스럽다. 드물어서가 아니라
 * **스스로 빛을 내기 때문이다.**
 *
 * 그래서 기준은 하나다 — **제 빛을 내는가.** 그러면 규칙이 배울 수 있는 것이 된다:
 * 화면이 물들면 빛나는 것이 얹혔다는 뜻이고, 물들지 않으면 그냥 물건이다.
 * 금메달·반지·유리조각처럼 **반짝이기만 하는** 것은 넣지 않았다. 빛을 되쏘는 것과
 * 내는 것은 다르고, 그 선을 풀면 결국 밝은 색 물건이 전부 들어와 원래대로 돌아간다.
 *
 * 재질 표(`materials.ts`)로 대신할 수 없다. `spark`는 번개·별똥별·별가루 셋뿐이고,
 * 햇빛·달·미러볼은 소리가 유리에 가까워 `glass`에 앉아 있다 — 귀에는 그게 맞고
 * 눈에는 아니다. 소리의 분류와 빛의 분류는 같은 표를 쓸 수 없다.
 */
const GLOWING_IDS: ReadonlySet<string> = new Set([
  /* 하늘에서 빛나는 것 */
  'bolt',
  'shooting-star',
  'stardust',
  'sunlight',
  'crescent-moon',
  'gold-star',
  /* 불을 켠 것 */
  'candle',
  'flashlight',
  /* 빛을 뿜거나 흩뿌리는 것 — 미러볼은 제 빛이 없지만 빛을 흩는 것이 그 물건의 정체다 */
  'magic-wand',
  'mirror-ball',
])

function glows(id: string): boolean {
  return GLOWING_IDS.has(id)
}

export { GLOWING_IDS, glows }
